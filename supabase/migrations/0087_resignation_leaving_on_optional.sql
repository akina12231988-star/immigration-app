-- 退職＜随時報告＞で、退職希望は出ているが退職日がまだ決まっていない人も
-- 記録できるようにする（退職日を空のまま保存できる）。
--
-- 退職日が空の記録は、一覧に「退職日を聞いて！！」のアラートを出して
-- あとから入れてもらう。届出書（参考様式）の作成には退職日が要るので、
-- 空のままでは様式を作れないように画面側で止めている。
--
-- 何度実行しても安全。
alter table resignations alter column leaving_on drop not null;

comment on column resignations.leaving_on is
  '退職日（未定のときは空。空のときは一覧に「退職日を聞いて！！」と出る）';

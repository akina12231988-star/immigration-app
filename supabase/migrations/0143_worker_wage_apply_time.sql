-- 適用開始日を空（null）にできるようにし、空は「雇用開始日から適用」を表す。
-- 雇用開始日が決まって在籍中になったら、その日が適用開始日として入り、
-- 理由「申請時」は「採用時」に変わる（src/lib/wage.ts・画面側で行う）。

-- 氏名の突き合わせ用（空白を取って大文字にそろえる）
create temporary view tmp_visa_match as
select
  t.*,
  (select count(*) from workers w
    where upper(regexp_replace(w.name, '[[:space:]　]', '', 'g'))
        = upper(regexp_replace(t.name, '[[:space:]　]', '', 'g'))) as hit_count,
  (select min(w.id) from workers w
    where upper(regexp_replace(w.name, '[[:space:]　]', '', 'g'))
        = upper(regexp_replace(t.name, '[[:space:]　]', '', 'g'))) as worker_id
from tmp_visa_import t;

-- 取り込み（1人に決まる名前だけ・同じ許可日と在留資格が無いものだけ）
insert into worker_visa_history (worker_id, permit_date, status, kind, expiry_date, card_no, note)
select m.worker_id, m.permit_date, m.status, m.kind, m.expiry_date, m.card_no, m.note
from tmp_visa_match m
where m.hit_count = 1
  and not exists (
    select 1 from worker_visa_history h
    where h.worker_id = m.worker_id
      and h.permit_date = m.permit_date
      and h.status = m.status
  );

-- 結果の表: 取り込んだ件数と、紐づかなかった名前
select '取り込み済みの件数' as 区分, null::text as 名前,
       count(*)::text as 件数
from worker_visa_history h
where h.note like '%在籍履歴から取り込み'
union all
select '外国人が見つからない' as 区分, m.name, count(*)::text
from tmp_visa_match m where m.hit_count = 0 group by m.name
union all
select '同じ名前の人が複数いる' as 区分, m.name, count(*)::text
from tmp_visa_match m where m.hit_count > 1 group by m.name
order by 1, 2;


export const LATEST_RELEASE_DATE = RELEASE_NOTES[0]?.date ?? "";

// 未読のお知らせ（最後に読んだ日より後のもの）。
// lastReadDate が空なら、直近の1日分だけを未読として出す（初回に全件バッジが付かないように）
export function unreadReleaseNotes(lastReadDate: string): ReleaseNote[] {
  if (!lastReadDate) {
    return RELEASE_NOTES.filter((n) => n.date === LATEST_RELEASE_DATE);
  }
  return RELEASE_NOTES.filter((n) => n.date > lastReadDate);
}

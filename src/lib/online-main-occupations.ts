// 分野から主たる職種の候補を推定する（未登録のときの目安。農業・漁業・林業は農林漁業従事者 など）
export function suggestedMainOccupation(industry: string | null | undefined): string {
  const key = (industry ?? "").normalize("NFKC").replace(/分野$/, "").trim();
  if (["農業", "漁業", "林業"].includes(key)) return "農林漁業従事者";
  if (key === "介護") return "介護福祉士";
  if (["ビルクリーニング", "リネンサプライ"].includes(key)) return "運搬・清掃・包装等従事者";
  if (key === "建設") return "建設従事者（建設躯体工事従事者を除く）";
  if (["自動車整備"].includes(key)) return "機械整備・修理従事者";
  if (["外食業"].includes(key)) return "調理";
  if (["物流倉庫"].includes(key)) return "運搬・清掃・包装等従事者";
  return "";
}

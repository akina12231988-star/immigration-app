export function suggestedMainIndustry(industryField: string | null | undefined): string {
  const key = (industryField ?? "")
    .normalize("NFKC")
    .split(/[／/]/)[0]
    .replace(/分野$/, "")
    .replace(/船用工業/, "舶用工業")
    .trim();
  return SUGGESTED[key] ?? "";
}
